# -*- coding: utf-8 -*-
import os
import sys
import json
import tempfile
import unittest

sys.dont_write_bytecode = True

ROOT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if ROOT_DIR not in sys.path:
    sys.path.insert(0, ROOT_DIR)


class TestRpgMakerMzMod(unittest.TestCase):
    def _make_mock_rmmz_game(self, root):
        game_root = os.path.join(root, "RealmWalker")
        os.makedirs(os.path.join(game_root, "data"), exist_ok=True)
        os.makedirs(os.path.join(game_root, "js", "plugins"), exist_ok=True)

        # Write Game.exe
        with open(os.path.join(game_root, "Game.exe"), "w", encoding="utf-8") as f:
            f.write("fake exe")

        # Write package.json
        with open(os.path.join(game_root, "package.json"), "w", encoding="utf-8") as f:
            json.dump({"name": "rmmz-game", "main": "index.html"}, f)

        # Write System.json
        with open(os.path.join(game_root, "data", "System.json"), "w", encoding="utf-8") as f:
            json.dump({"gameTitle": "RealmWalker", "locale": "en_US"}, f)

        # Write rmmz_core.js
        with open(os.path.join(game_root, "js", "rmmz_core.js"), "w", encoding="utf-8") as f:
            f.write("// rmmz_core")

        # Write plugins.js
        plugins_js_content = (
            "// Generated by RPG Maker.\n"
            "var $plugins =\n"
            "[\n"
            '{"name":"VisuMZ_0_CoreEngine","status":true,"description":"","parameters":{}}\n'
            "];\n"
        )
        with open(os.path.join(game_root, "js", "plugins.js"), "w", encoding="utf-8") as f:
            f.write(plugins_js_content)

        return game_root

    def test_detects_rpgmaker_mz_engine(self):
        from install_tts_mod import detect_game_engine

        with tempfile.TemporaryDirectory() as tmpdir:
            game_root = self._make_mock_rmmz_game(tmpdir)
            engine, detected_root = detect_game_engine(game_root)
            self.assertEqual(engine, "rpgmaker_mz")
            self.assertEqual(os.path.normpath(detected_root), os.path.normpath(game_root))

    def test_detects_nested_rpgmaker_mz_engine(self):
        from install_tts_mod import detect_game_engine

        with tempfile.TemporaryDirectory() as tmpdir:
            outer = os.path.join(tmpdir, "OuterFolder")
            os.makedirs(outer, exist_ok=True)
            game_root = self._make_mock_rmmz_game(outer)

            engine, detected_root = detect_game_engine(outer)
            self.assertEqual(engine, "rpgmaker_mz")
            self.assertEqual(os.path.normpath(detected_root), os.path.normpath(game_root))

    def test_build_install_plan_for_rpgmaker_mz(self):
        from install_tts_mod import build_install_plan

        with tempfile.TemporaryDirectory() as tmpdir:
            game_root = self._make_mock_rmmz_game(tmpdir)
            entries = build_install_plan(game_root)
            destinations = {os.path.normpath(e.destination) for e in entries}

            # Backend and launcher files in game root
            for fname in ("tts_server.py", "tts_engines.py", "text_cleaner.py", "run_backend.bat", "JOGAR_COM_TTS.bat"):
                self.assertIn(os.path.normpath(os.path.join(game_root, fname)), destinations)

            # Plugin in js/plugins/TTSModMZ.js
            self.assertIn(
                os.path.normpath(os.path.join(game_root, "js", "plugins", "TTSModMZ.js")),
                destinations
            )

            # Voice map in game root
            self.assertIn(
                os.path.normpath(os.path.join(game_root, "voice_map.json")),
                destinations
            )

    def test_install_game_registers_plugin_in_plugins_js(self):
        from install_tts_mod import install_game

        with tempfile.TemporaryDirectory() as tmpdir:
            game_root = self._make_mock_rmmz_game(tmpdir)
            result = install_game(game_root)

            self.assertEqual(result.engine, "rpgmaker_mz")
            self.assertTrue(os.path.exists(os.path.join(game_root, "js", "plugins", "TTSModMZ.js")))
            self.assertTrue(os.path.exists(os.path.join(game_root, "voice_map.json")))
            self.assertTrue(os.path.exists(os.path.join(game_root, "JOGAR_COM_TTS.bat")))

            # Check plugins.js registration
            plugins_js_path = os.path.join(game_root, "js", "plugins.js")
            with open(plugins_js_path, "r", encoding="utf-8") as f:
                content = f.read()

            self.assertIn('"name":"TTSModMZ"', content)
            self.assertIn('"status":true', content)
            # Make sure existing plugin was preserved
            self.assertIn('"name":"VisuMZ_0_CoreEngine"', content)

    def test_realmwalker_voice_map_rules(self):
        voice_map_path = os.path.join(ROOT_DIR, "rpgmaker_mz_mod", "voice_map.json")
        self.assertTrue(os.path.exists(voice_map_path), "voice_map.json deve existir em rpgmaker_mz_mod/")

        with open(voice_map_path, "r", encoding="utf-8") as f:
            vmap = json.load(f)

        # Protagonist / Narrator rule
        self.assertEqual(vmap.get("default"), "am_onyx")
        self.assertEqual(vmap.get("narrator"), "am_onyx")
        self.assertEqual(vmap.get("Reid"), "am_onyx")
        self.assertEqual(vmap.get(r"\N[1]"), "am_onyx")

        # Female characters must be in af_ pool
        females = [
            "Lyriana", "Felina", "Alice", "Queen Alice", "Vespera",
            "Astrid", "Liora", "Isolde", "Morgana", "Aria", "Selene",
            "Rowena", "Urza", "Margery", "Sister Margery", "Elara", "Princess Elara"
        ]
        for name in females:
            voice = vmap.get(name)
            self.assertIsNotNone(voice, f"Personagem feminina '{name}' deve estar no voice_map")
            self.assertTrue(voice.startswith("af_"), f"Voz de '{name}' ({voice}) deve comecar com 'af_'")

        # Male characters must be in am_ pool
        males = ["Dad", "Gorok", "Dante", "King Arthur", "Donald", "Valroth"]
        for name in males:
            voice = vmap.get(name)
            self.assertIsNotNone(voice, f"Personagem masculino '{name}' deve estar no voice_map")
            self.assertTrue(voice.startswith("am_"), f"Voz de '{name}' ({voice}) deve comecar com 'am_'")

    def test_register_rpgmaker_mz_plugin_idempotent(self):
        from install_tts_mod import register_rpgmaker_mz_plugin

        with tempfile.TemporaryDirectory() as tmpdir:
            game_root = self._make_mock_rmmz_game(tmpdir)
            self.assertTrue(register_rpgmaker_mz_plugin(game_root))
            self.assertTrue(register_rpgmaker_mz_plugin(game_root))

            plugins_js_path = os.path.join(game_root, "js", "plugins.js")
            with open(plugins_js_path, "r", encoding="utf-8") as f:
                content = f.read()

            self.assertEqual(content.count('"name":"TTSModMZ"'), 1)

    def test_tts_mod_mz_protocol_line_contract(self):
        js_path = os.path.join(ROOT_DIR, "rpgmaker_mz_mod", "TTSModMZ.js")
        self.assertTrue(os.path.exists(js_path), "TTSModMZ.js deve existir em rpgmaker_mz_mod/")
        with open(js_path, "r", encoding="utf-8") as f:
            content = f.read()

        # Protocol invariant: lines sent to tts_server.py must be raw text without 'SPEAK ' prefix
        self.assertNotIn("`SPEAK ${text}\\n`", content)
        self.assertNotIn('"SPEAK " +', content)
        self.assertIn('"STOP\\n"', content)
        self.assertIn("`SET_VOICE:${voice}\\n`", content)
        self.assertIn("`SET_SPEED:${this.speed.toFixed(2)}\\n`", content)
        self.assertIn("`${text}\\n`", content)


if __name__ == "__main__":
    unittest.main()
